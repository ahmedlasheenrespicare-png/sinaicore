/** flatten a keyframe into the numbers the timeline tweens */
export function frameToTween(kf) {
  return {
    camX: kf.cam[0],
    camY: kf.cam[1],
    camZ: kf.cam[2],
    tx: kf.target[0],
    ty: kf.target[1],
    tz: kf.target[2],
    fov: kf.fov,
    explode: kf.explode,
    align: kf.align,
    sort: kf.sort,
    wash: kf.wash,
    lattice: kf.lattice,
    rotate: kf.rotate,
    particles: kf.particles,
    ring: kf.ring,
    specimenOpacity: kf.specimenOpacity,
  }
}

