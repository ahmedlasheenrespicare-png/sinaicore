/* ---------------------------------------------------------------- *
 * Chapters. `body` is an array of blocks, read in order.
 *   p      — a paragraph
 *   num    — a numbered margin note
 *   fig    — a figure with a real caption (the reference's counter)
 *   quote  — a pull quote
 *   list   — small definition rows
 * ---------------------------------------------------------------- */
export type Block =
  | { kind: 'p'; text: string; drop?: boolean }
  | { kind: 'note'; n: string; title: string; text: string }
  | {
      kind: 'fig'
      src: string
      alt: string
      caption: string
      tag: string
      /** photo without a printed mark in it — safe to crop tight */
      bare?: boolean
      /** CSS aspect-ratio, per picture, so a crop never cuts a product */
      ratio?: string
    }
  | { kind: 'quote'; text: string; cite: string }
  | { kind: 'rows'; title: string; rows: [string, string][] }

export type Chapter = {
  id: string
  n: string
  title: string
  sub: string
  lead: string
  blocks: Block[]
}

